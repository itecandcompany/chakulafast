// Concatenates every migration, in order, into a single file you can paste
// into the Supabase SQL editor in one go.
//
//   npm run db:bundle
//
// For when there's no Supabase CLI to hand. `supabase db push` remains the
// better route where it's available, because it records which migrations have
// been applied; this bundle does not, so it is a one-shot "set up a fresh
// project" tool rather than something to re-run after every change.
//
// The output is generated and gitignored — regenerate it rather than editing
// it, or it will drift from supabase/migrations/ and quietly become a lie.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase", "migrations");
const out = path.join(root, "supabase", "schema.generated.sql");

const files = fs.readdirSync(dir).sort();

const header = `-- ===========================================================================
-- ChakulaFast — complete schema
--
-- GENERATED by \`npm run db:bundle\` from supabase/migrations/ on
-- ${new Date().toISOString()}.
-- Do not edit: change the migrations and regenerate.
--
-- To apply: open your Supabase project > SQL Editor > New query, paste this
-- whole file, and Run. It is safe on a fresh project and expects to be run
-- exactly once.
--
-- ${files.length} migrations, in order:
${files.map((f) => `--   ${f}`).join("\n")}
-- ===========================================================================

`;

const body = files
  .map((f) => {
    const sql = fs.readFileSync(path.join(dir, f), "utf8").trimEnd();
    return ["", "-- " + "=".repeat(73), `-- ${f}`, "-- " + "=".repeat(73), "", sql, ""].join("\n");
  })
  .join("\n");

fs.writeFileSync(out, header + body, "utf8");

const kb = (fs.statSync(out).size / 1024).toFixed(1);
console.log(`Wrote supabase/schema.generated.sql — ${files.length} migrations, ${kb} kB`);
console.log("Paste it into the Supabase SQL editor and run it once.");
